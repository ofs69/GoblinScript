//! `cargo xtask dist` -- build the release binary and pack the distribution zip
//! into `dist/`. The host decides which one: a Windows host packs the Windows
//! zips and a Linux host the Linux one, and the release workflow runs one of
//! each.
//!
//!   goblinscript-<ver>-windows-dml.zip
//!                               exe (embedded bundle) + DirectML.dll.
//!                               Runs on any DirectX 12 GPU (NVIDIA / AMD /
//!                               Intel) as-is. This is the default artifact
//!                               on Windows.
//!
//!   goblinscript-<ver>-linux-cuda.zip
//!                               binary (embedded bundle) + Microsoft's ONNX
//!                               Runtime + NVIDIA's own CUDA 12 and cuDNN 9.
//!                               CUDA is the floor off Windows rather than an
//!                               option, so there is one Linux zip and it
//!                               carries everything but the NVIDIA card and
//!                               its driver.
//!
//!   goblinscript-<ver>-windows-cuda.zip
//!                               `cargo xtask dist --cuda` ALSO packs this on
//!                               Windows: the same two runtimes, on an NVIDIA
//!                               card only. On an RTX 4090 it reads 60 ms
//!                               against DirectML's 72 -- one sixth off every
//!                               draft.
//!
//! A build has ONE GPU provider and no fallback to another, because the two do
//! not live in one ONNX Runtime: the DirectML zip links the runtime the `ort`
//! crate downloads, and the CUDA zips link Microsoft's, which has a CUDA EP
//! and no DirectML EP at all. Microsoft's is what reaches a Blackwell card --
//! the `ort` build's CUDA provider stops at sm_90 and carries no PTX to JIT
//! past it.
//!
//! On Windows the CUDA build is a SECOND zip rather than the only one because
//! those two runtimes weigh ~1.6 GB, which every AMD and Intel owner would
//! carry for nothing and could not use. The libraries are IN a zip rather than
//! a thing to go and install, because ONNX Runtime loads its provider library
//! in a way that does not resolve these dependencies from PATH:
//! `cudnn64_9.dll` ON PATH is reported missing, and only a copy beside the
//! binary is found.
//!
//! `CUDA_LIBS_DIR` (default `cuda-libs/`) and `ORT_LIB_LOCATION` are where the
//! two are read from -- the release workflow fills them, and a missing file
//! stops the pack by name. `ORT_LIB_LOCATION` is the variable cargo links
//! against as well, so a zip cannot carry a runtime its binary was not built
//! for.
//!
//! Every zip ships THIRD-PARTY-NOTICES.txt (generated by cargo-about) -- a
//! license obligation, so a missing file stops the pack. A CUDA zip's copy
//! carries NVIDIA's redistribution terms as well.
//!
//! Whatever sits in `bundle/` is what gets baked in; the manifest's checkpoint
//! is printed so a stale bundle is noticed before it ships.

use anyhow::{bail, Context, Result};
use std::fs::File;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;
use zip::write::SimpleFileOptions;
use zip::CompressionMethod;

fn root() -> PathBuf {
    // xtask lives at <goblinscript>/xtask
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().to_path_buf()
}

/// The main crate's version, straight out of its Cargo.toml `[package]`.
fn crate_version(root: &Path) -> Result<String> {
    let toml = std::fs::read_to_string(root.join("Cargo.toml"))?;
    let mut in_package = false;
    for line in toml.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_package = t == "[package]";
        } else if in_package {
            if let Some(v) = t.strip_prefix("version") {
                if let Some(v) = v.trim_start().strip_prefix('=') {
                    return Ok(v.trim().trim_matches('"').to_string());
                }
            }
        }
    }
    bail!("no [package] version in {}", root.join("Cargo.toml").display());
}

/// One cargo build, against one ONNX Runtime.
///
/// `ort` is the runtime to link: `Some` for a CUDA build, which links
/// Microsoft's own package, and `None` for the DirectML build, which links the
/// one the `ort` crate downloads. The variable is REMOVED rather than left
/// alone in the `None` case, because a shell that exported it for a CUDA build
/// would otherwise hand the DirectML build a runtime with no DirectML EP in
/// it, and that failure only shows up on a user's machine.
fn build(root: &Path, features: &str, ort: Option<&Path>) -> Result<()> {
    println!("\ncargo build --release --features {features}");
    let mut cmd = Command::new("cargo");
    cmd.current_dir(root).args(["build", "--release", "--features", features]);
    match ort {
        Some(dir) => {
            println!("  against the ONNX Runtime in {}", dir.display());
            cmd.env("ORT_LIB_LOCATION", dir).env("ORT_PREFER_DYNAMIC_LINK", "1");
        }
        None => {
            cmd.env_remove("ORT_LIB_LOCATION").env_remove("ORT_PREFER_DYNAMIC_LINK");
        }
    }
    let ok = cmd.status().context("could not run cargo")?.success();
    if !ok {
        bail!("build with --features {features} failed");
    }
    Ok(())
}

/// The boot screen with its version filled in.
fn banner(ver: &str) -> String {
    GOBLIN_ART.replace("%VER%", ver)
}

/// Every catalog in `languages/`, as (source, archive name). Enumerated rather
/// than listed, like the soundtrack: adding a language is dropping a file in a
/// folder, for us exactly as much as for the person translating one.
fn languages(root: &Path) -> Result<Vec<(PathBuf, String)>> {
    let dir = root.join("languages");
    let mut out: Vec<(PathBuf, String)> = std::fs::read_dir(&dir)
        .with_context(|| format!("{} is missing", dir.display()))?
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|x| x.to_str()) == Some("json"))
        .map(|p| {
            let name = format!("languages/{}", p.file_name().unwrap_or_default().to_string_lossy());
            (p, name)
        })
        .collect();
    out.sort_by(|a, b| a.1.cmp(&b.1));
    if !out.iter().any(|(_, n)| n == "languages/en-US.json") {
        bail!("languages/en-US.json is missing -- it is the template every translation starts from");
    }
    Ok(out)
}

fn pack(out: &Path, files: &[(PathBuf, String)], readme: &str) -> Result<()> {
    let mut z = zip::ZipWriter::new(
        File::create(out).with_context(|| format!("create {}", out.display()))?,
    );
    let opts = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);
    z.start_file("README.txt", opts)?;
    z.write_all(readme.as_bytes())?;
    for (src, name) in files {
        // A zip carries no mode unless told, and a Linux unzip then writes
        // the binary and the library without the execute bit. `contains`
        // rather than `ends_with`, because a soname carries its major version
        // after the suffix: `libcudnn.so.9` is a library too.
        let mode = if name.ends_with(".exe") || name.contains(".so") || name == "goblinscript" {
            0o755
        } else {
            0o644
        };
        z.start_file(name.as_str(), opts.unix_permissions(mode))?;
        let mut f = File::open(src)
            .with_context(|| format!("{} missing -- did the build run?", src.display()))?;
        std::io::copy(&mut f, &mut z)?;
    }
    z.finish()?;
    let mb = std::fs::metadata(out)?.len() as f64 / 1e6;
    println!("  -> {} ({mb:.0} MB)", out.display());
    Ok(())
}

