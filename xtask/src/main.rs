/// The operator's guide for one package: the common text with its platform
/// slots filled.
///
/// `cuda` is what the reader's card has to be, and the two Windows packages
/// differ on exactly that line: the DirectML one takes any DirectX 12 card,
/// and the CUDA one takes an NVIDIA card and stops on anything else.
fn readme(ver: &str, windows: bool, cuda: bool) -> String {
    let start = if windows {
        "Double-click goblinscript.exe."
    } else {
        "Run ./goblinscript in a terminal."
    };
    const CARD_CUDA: &str = "NVIDIA, GTX 10 series or newer, with NVIDIA's\n                             own driver, version 525 or newer";
    let needs = if windows {
        NEEDS_WINDOWS
            .replace("%CARD%", if cuda { CARD_CUDA } else { "DirectX 12: NVIDIA, AMD or Intel" })
    } else {
        NEEDS_LINUX.to_string()
    };
    format!(
        "{}\n{}",
        banner(ver),
        README_COMMON.replace("%START%", start).replace("%NEEDS%", &needs)
    )
}

/// NVIDIA's own runtime, packed beside the binary in every CUDA zip.
///
/// This is the MINIMUM that draws a correct draft, measured against the
/// runtime the CUDA packages actually carry by removing libraries until a
/// graph broke. Three of them are direct imports of the CUDA provider --
/// `cudart`, `cublas`, `cublasLt` -- and the rest are cuDNN, which the
/// provider opens by name at the first node that needs it. Dropping
/// `cudnn_engines_precompiled` fails the shot-cut detector's first
/// convolution, and dropping cuDNN entirely fails its `ReduceL2`.
///
/// What is NOT here is as measured as what is: `cudnn_adv`, `cudnn_cnn`,
/// `cufft`, `curand` and `nvrtc` all ship with CUDA and none of them is
/// reached -- 642 MB that changed no timing and broke no graph.
///
/// They are IN the zip rather than a thing to go and install because ONNX
/// Runtime loads its provider library in a way that does not resolve these
/// dependencies from PATH: `cudnn64_9.dll` ON PATH is reported missing, and
/// only a copy beside the binary is found. An installed CUDA is not enough.
///
/// The weight is real (`cublasLt` and `cudnn_engines_precompiled` are ~500 MB
/// each and neither has a smaller form), which is why the Windows CUDA build
/// is a zip of its own. On Linux there is no choice to make: the CUDA provider
/// is the only GPU path, so its libraries go in the one zip.
///
/// A Linux name is the SONAME, not the file in NVIDIA's archive: the archive
/// ships `libcudnn.so.9.10.2` with `libcudnn.so.9` pointing at it, and the
/// loader asks for the soname. The pack reads through the link, so the zip
/// holds one real file under the name the loader looks for.
